"""UT02-80: the committed synth_small goldens carry the current `GENERATOR_VERSION`.

The goldens (`tests/fixtures/golden/synth_small_{counts,core}.json`) are only checked by the
slow IT02-31, so this fast guard makes a generator change fail in suite (a) until they are
regenerated (T02-22b).
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from tests.support.synth_build import GOLDEN_CORE, GOLDEN_COUNTS

from tools.synth import GENERATOR_VERSION

pytestmark = pytest.mark.unit

REGENERATE = (
    "regenerate the goldens (about 70 s): "
    "`PYTHONUTF8=1 uv run python -m tests.support.synth_build <empty_root> <cfg_root>`"
)


@pytest.mark.parametrize("golden", [GOLDEN_COUNTS, GOLDEN_CORE], ids=lambda p: p.name)
def test_ut02_80_golden_generator_version_is_current(golden: Path) -> None:
    """UT02-80 each synth_small golden's `generator_version` equals `GENERATOR_VERSION`."""
    recorded = json.loads(golden.read_text(encoding="utf-8")).get("generator_version")
    assert recorded == GENERATOR_VERSION, (
        f"{golden.name} was generated by {recorded!r} but tools.synth is "
        f"{GENERATOR_VERSION!r}: {REGENERATE}"
    )
