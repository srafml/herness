# CO-T04-22d: patches a T11 synth_mappings fragment defect; delete once T11 fixes it.
_LOWER: Final = ("Task", "Epic", "Feature", "Story", "Bug", "Initiative")
SYNTH_ENUMS: Final[dict[str, dict[str, str]]] = {
    "jira.issue_type": {name: name.lower() for name in _LOWER},
    "jira.status_category_key": {"new": "todo", "indeterminate": "in_progress", "done": "done"},
    "jira.status_category": {"To Do": "todo", "In Progress": "in_progress", "Done": "done"},
    "servicenow.change_type": {k: k for k in ("normal", "emergency", "standard")},
    "servicenow.change_close_code": {
        k: k for k in ("successful", "unsuccessful", "backed_out", "successful_with_issues")
    },
    "monitoring.severity": {k: k for k in ("critical", "major", "minor", "warning", "info")},
}
# Design 11 §5.1.5: the planted clusters' template families and root causes.
ROOT_CAUSE: Final = {"T2": "capacity", "T2c": "access_identity"}
_SERVICE_PLANT: Final = {"T2": "T2_roi_epic", "T2c": "T2c_cluster_fix"}
_BUILD_CFG: Final = BuildSettings(memory_limit="16GB", threads=8)
_SOURCES_YAML: Final = "version: 1\nbuild:\n  threads: 8\n  memory_limit: 16GB\n"


def generate_root(seed: int, scale: str, root: Path, **overrides: object) -> Path:
    """Generate a synthetic root in-process (`tools/synth_data.py` `generate`, CLI
    `overrides` such as `workers`); return it."""
    from tools.synth_data import generate  # noqa: PLC0415 - heavy, only when generating

    generate(seed, scale, root, **overrides)
    herness_config.reset_config()  # generate caches the synth profile's config
    return root


def cluster_id(plant: str) -> str:
    """The `enrich.cluster` ID planted for `plant` (`T2` or `T2c`)."""
    return f"clu_truth_{plant.lower()}"


def _mappings(synth_root: Path) -> dict[str, Any]:
    text = (synth_root / "synth_mappings.yaml").read_text(encoding="utf-8")
    # CO-T04-22d (SN-f): the fragment's :cmdb_ci_service: prefix; delete once T11 fixes it.
    fragment = yaml.safe_load(text.replace(":cmdb_ci_service:", ":cmdb_ci:"))["mappings"]
    enums = fragment.setdefault("enums", {})
    for name, values in SYNTH_ENUMS.items():
        enums[name] = {**values, **enums.get(name, {})}
    return {"version": 1, **fragment}


def _metrics_yaml(cfg_dir: Path, as_of: datetime.date, window_days: int | None) -> None:
    path = cfg_dir / "metrics.yaml"
    doc = yaml.safe_load(path.read_text(encoding="utf-8"))
    doc["scoring"]["as_of"] = as_of  # a YAML date: the strict model rejects a string
    if window_days is not None:
        doc["scoring"]["funding"]["window_days"] = window_days
    path.write_text(yaml.safe_dump(doc, sort_keys=False), encoding="utf-8")


@dataclasses.dataclass(frozen=True)
class SynthEnv:
    """A generated synthetic root plus the config tree and ops store the tests use."""

    synth_root: Path
    cfg_dir: Path
    ops_db: Path
    truth: Truth

    @classmethod
    def create(
        cls, synth_root: Path, work: Path, *, funding_window_days: int | None = None
    ) -> SynthEnv:
        """Write the config tree under `work`; `funding_window_days` overrides the shipped
        365-day funding window (allowed 30..1095)."""
        truth = read_truth(synth_root)
        cfg_dir = write_full_config(work / "cfgroot")
        mappings = yaml.safe_dump(_mappings(synth_root), sort_keys=True)
        (cfg_dir / "mappings.yaml").write_text(mappings, encoding="utf-8")
        (cfg_dir / "sources.yaml").write_text(_SOURCES_YAML, encoding="utf-8")
        _metrics_yaml(cfg_dir, truth.end + datetime.timedelta(days=1), funding_window_days)
        return cls(synth_root, cfg_dir, work / "ops.sqlite", truth)

    @property
    def data_root(self) -> Path:
        """The generated `data/` folder (raw lake; warehouse files are written here too)."""
        return self.synth_root / "data"

    @property
    def layout(self) -> DataLayout:
        """The data layout of `data_root`."""
        return DataLayout.from_root(self.data_root)

    def activate(self) -> HernessConfig:
        """Load this config into the process cache and point the ops store at `ops_db`."""
        herness_config.reset_config()
        env = {"HERNESS_PATHS__DATA": str(self.data_root)}
        cfg = herness_config.init_config("local", config_dir=self.cfg_dir, env=env)
        reset_connections(path=self.ops_db)
        migrate()
        return cfg

    def open_build(self, build_id: str) -> duckdb.DuckDBPyConnection:
        """The writable connection of an existing build file."""
        return open_for_build(build_id, create=False, cfg=_BUILD_CFG, layout=self.layout)


def release() -> None:
    """Fixture teardown: drop the ops-store connections and the process-wide config cache
    `SynthEnv.activate` loaded (the reset the autouse `reset_herness_state` uses), so no
    tmp-folder config leaks into later test modules."""
    reset_connections()
    herness_config.reset_config()


def remove_builds(env: SynthEnv) -> None:
    """Delete the warehouse folder `env`'s builds wrote under its `data_root`, so a reused
    (cached) synthetic root is left as generated; then `release()`."""
    release()
    shutil.rmtree(env.layout.warehouse, ignore_errors=True)


def plant_enrichment(con: duckdb.DuckDBPyConnection, truth: Truth) -> None:
    """Write the enrichment a perfect enricher would: the T2 and T2c clusters (membership 1.0,
    the design 11 root cause, the plant's service) and the T3 incident-change links."""
    for plant, root_cause in ROOT_CAUSE.items():
        members = truth.members(plant)
        service = str(truth.plant(_SERVICE_PLANT[plant])["service_id"])
        cid = cluster_id(plant)
        con.execute(
            "INSERT INTO enrich.cluster (cluster_id, label, root_cause_category, size,"
            " service_ids, algorithm_version) VALUES (?, ?, ?, ?, [?], 'truth')",
            [cid, plant, root_cause, len(members), service],
        )
        con.executemany(
            "INSERT INTO enrich.cluster_member VALUES (?, ?, 1.0)", [[m, cid] for m in members]
        )
    pairs = truth.change_pairs()
    if pairs:
        con.executemany(
            "INSERT INTO enrich.incident_change_link VALUES (?, ?, 'truth', 1.0)",
            [list(pair) for pair in pairs],
        )


def _durations(result: Mapping[str, Any]) -> dict[str, int]:
    """The per-stage `durations_ms` of a `build_pipeline` job result."""
    raw = result["durations_ms"]
    assert isinstance(raw, Mapping)
    return {str(name): int(ms) for name, ms in raw.items()}


@dataclasses.dataclass(frozen=True)
class ScoredBuild:
    """A scored build file and the wall times of its stages (seconds); `build_durations_ms` is
    the `durations_ms` of the `build_pipeline` job result (T02-23)."""

    build_id: str
    report: ScoringReport
    build_s: float
    facts_s: float
    scoring_s: float
    build_durations_ms: Mapping[str, int] = dataclasses.field(default_factory=dict)


def scored_build(env: SynthEnv, *, promote: bool = True) -> ScoredBuild:
    """Build `env`'s lake, plant the enrichment, run stage 400 and `run_scoring` (default
    steps); the connection is closed afterwards and the build optionally made CURRENT."""
    env.activate()
    start = time.perf_counter()
    outcome = run_build_pipeline(FakeJobContext({"stages": ["build"]}))
    build_id = str(outcome.result["build_id"])
    build_s = time.perf_counter() - start
    con = env.open_build(build_id)
    try:
        plant_enrichment(con, env.truth)
        start = time.perf_counter()
        materialize_facts(con, build_id)
        facts_s = time.perf_counter() - start
        con.execute("CHECKPOINT")
        start = time.perf_counter()
        report = run_scoring(build_id, con=con)
        scoring_s = time.perf_counter() - start
        con.execute("CHECKPOINT")
    finally:
        con.close()
    if promote:
        write_current(build_id, layout=env.layout)
    durations = _durations(outcome.result)
    return ScoredBuild(build_id, report, build_s, facts_s, scoring_s, durations)
